namespace ArtGen;

/// <summary>Built-in 5x7 bitmap font: A-Z, 0-9 and a few symbols. Lower case is drawn as upper case.</summary>
public static class BitmapFont
{
    /// <summary>Glyph width in pixels.</summary>
    public const int GlyphWidth = 5;

    /// <summary>Glyph height in pixels.</summary>
    public const int GlyphHeight = 7;

    // Each glyph: 7 rows, top to bottom, bit 4 = leftmost pixel.
    private static readonly Dictionary<char, byte[]> Glyphs = new()
