        ['?'] = [0x0E, 0x11, 0x01, 0x02, 0x04, 0, 0x04],
        ['/'] = [0x01, 0x01, 0x02, 0x04, 0x08, 0x10, 0x10],
    };

    /// <summary>True when the font has a glyph for <paramref name="c"/> (case-insensitive).</summary>
    public static bool Has(char c) => Glyphs.ContainsKey(char.ToUpperInvariant(c));

    /// <summary>Pixel width of <paramref name="text"/> (1px spacing between glyphs).</summary>
    public static int Measure(string text) => text.Length == 0 ? 0 : (text.Length * (GlyphWidth + 1)) - 1;

    /// <summary>Draws text with its top-left at (x, y). Unknown characters draw as '?'.</summary>
    public static void Draw(Canvas canvas, string text, int x, int y, Rgba color)
    {
        foreach (char raw in text)
        {
            char c = char.ToUpperInvariant(raw);
            byte[] rows = Glyphs.TryGetValue(c, out byte[]? g) ? g : Glyphs['?'];
            for (int j = 0; j < GlyphHeight; j++)
            {
                for (int i = 0; i < GlyphWidth; i++)
                {
                    if ((rows[j] & (1 << (GlyphWidth - 1 - i))) != 0)
                    {
                        canvas.Set(x + i, y + j, color);
                    }
                }
            }

            x += GlyphWidth + 1;
        }
    }

    /// <summary>Draws text centred on <paramref name="centerX"/> with a 1px outline for readability.</summary>
    public static void DrawLabel(Canvas canvas, string text, int centerX, int y, Rgba color, Rgba outline)
    {
        int x = centerX - (Measure(text) / 2);
        for (int dy = -1; dy <= 1; dy++)
        {
            for (int dx = -1; dx <= 1; dx++)
            {
                if (dx != 0 || dy != 0)
                {
                    Draw(canvas, text, x + dx, y + dy, outline);
                }
            }
        }

        Draw(canvas, text, x, y, color);
    }
}
